const ROAST_TOAST_API = 'https://roast-toast-api.traffictorch.workers.dev';
const AUTH_API = 'https://traffic-torch-auth.traffictorch.workers.dev';

function extractPunchyLine(md, maxLen = 95) {
  const raw = String(md || '');
  const lines = raw.split('\n')
    .map(l => l
      .replace(/^[#>*\-\s]+/, '')
      .replace(/\*\*/g, '')
      .replace(/^["'`]+|["'`]+$/g, '')
      .trim())
    .filter(l => l.length > 10)
    .filter(l => !/^[A-Z][\w\s]{1,40}:\s*$/i.test(l))
    .filter(l => !/^(Design Aesthetic|Overview|Summary|Purpose|Target Use Cases|Core Pillars):?$/i.test(l));
  const first = lines[0] || '';
  const sentence = (first.match(/^[^.!?]+[.!?]/) || [first])[0].trim();
  return sentence.length > maxLen
    ? sentence.slice(0, maxLen).replace(/\s+\S*$/, '') + '…'
    : sentence;
}

export function extractUrl(text) {
  if (!text) return null;
  const urlRegex = /(https?:\/\/[^\s]+)|(?:^|\s)((?:www\.)?[a-zA-Z0-9\-]+\.[a-zA-Z]{2,}(?:\/[^\s]*)?)/i;
  const match = text.match(urlRegex);
  if (!match) return null;
  let url = match[1] || match[2];
  if (url && !/^https?:\/\//i.test(url)) url = 'https://' + url;
  try { new URL(url); return url; } catch { return null; }
}

export function isUrl(s) {
  return !!extractUrl(s);
}

export async function callRoastToast({ mode, input }) {
  const token = localStorage.getItem('authToken') || '';
  const res = await fetch(ROAST_TOAST_API + '/api/roast-toast', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      ...(token ? { 'Authorization': 'Bearer ' + token } : {})
    },
    body: JSON.stringify({ mode, input })
  });
  const data = await res.json().catch(() => ({ ok: false, error: 'Invalid server response' }));
  return data;
}

export async function publishRoastToast({ mode, input, inputType, og, assessmentMd }) {
  const token = localStorage.getItem('authToken') || '';
  const hostname = og && og.hostname ? og.hostname : null;
  const subject = inputType === 'url'
    ? (hostname || extractUrl(input) || input)
    : (input.length > 80 ? input.slice(0, 77) + '…' : input);
  
  const extractedUrl = extractUrl(input) || '';
  let cleanMd = String(assessmentMd || '').replace(/^(Traffic Torch AI:|Roast:|Toast:)\s*/i, '').trim();
  const punchy = extractPunchyLine(cleanMd);
  const title = (punchy || subject).slice(0, 120);
  const inputLabel = inputType === 'url' ? 'Website' : 'Idea';
  const body = [
    `**${inputLabel}:**`,
    input,
    '',
    '---',
    '',
    `**Traffic Torch AI ${mode === 'toast' ? 'Toast' : 'Roast'}:**`,
    assessmentMd,
    '',
    '---',
    `_Generated by Traffic Torch AI_`
  ].join('\n').slice(0, 6000);

  const res = await fetch(AUTH_API + '/api/posts', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      ...(token ? { 'Authorization': 'Bearer ' + token } : {})
    },
    body: JSON.stringify({
      post_type: 'roast_toast',
      category: mode,
      title,
      body_md: body,
      url: extractedUrl
    })
  });
  const data = await res.json().catch(() => ({ error: 'Invalid server response' }));
  return data;
}
